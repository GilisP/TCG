using System;
using System.Collections.Generic;
using System.Linq;
namespace TCG.Foundation
{
    public sealed partial class Match
    {
        // Authoritative candidates. This deliberately avoids enumerating the exponential
        // set of every attack group/block assignment; each emitted action is legal.
        public IReadOnlyList<Command> DecisionCommandsFor(int seat)
        {
            if(IsRemoteView)throw new InvalidOperationException("Decisions must be generated by the authority.");
            var result=new List<Command>();
            if(Over||seat<0||seat>=seats.Length||seat!=Controller||seats[seat].Eliminated)return result;
            Command New(ActionKind kind,int target=-1,int unit=-1,int pile=-1,string card=null)=>new Command{player=seat,revision=Revision,kind=kind,target=target,unit=unit,pile=pile,card=card};
            if(Choice!=null){foreach(var o in Choice.Options)result.Add(New(ActionKind.Choose,o.Key));return result;}
            if(Defense!=null)
            {
                var battle=Defense;
                var ids=cells[battle.Target].pieces.Where(p=>p.Owner==battle.Defender&&p.Card.Kind!=CardType.Equipment&&p.Card.Kind!=CardType.Enchantment).Select(p=>p.Id).ToList();
                if(cells[battle.Target].CapitalOwner==battle.Defender)ids.Add(-1);
                foreach(int id in ids){var c=New(ActionKind.Defend);c.blockers=Enumerable.Repeat(id,battle.Attackers.Length).ToArray();result.Add(c);}
                if(ids.Count>1){var c=New(ActionKind.Defend);c.blockers=Enumerable.Range(0,battle.Attackers.Length).Select(i=>ids[i%ids.Count]).ToArray();result.Add(c);}
                return result;
            }
            if(Phase==Stage.Draw&&Priority==Active&&stack.Count==0){for(int pile=0;pile<4;pile++){result.Add(New(ActionKind.DrawMain,pile:pile));result.Add(New(ActionKind.DrawTerrain,pile:pile));}return result;}
            var view=ViewFor(seat);
            var attacks=new Dictionary<int,List<int>>();
            foreach(string key in view.legal)
            {
                var parts=key.Split(new[]{':'},4);int a=int.Parse(parts[1]),b=int.Parse(parts[2]);string card=parts[3];
                switch(parts[0])
                {
                    case "place": for(int pile=0;pile<4;pile++)if(seats[seat].Top(pile)!=null)result.Add(New(ActionKind.Place,a,pile:pile));break;
                    case "play":result.Add(New(ActionKind.Play,a,b,card:card));break;
                    case "summon":result.Add(New(ActionKind.SummonCommander,a));break;
                    case "move":result.Add(New(ActionKind.Move,b,a));break;
                    case "attack":
                        if(cells[b].pieces.Where(p=>p.Card.Kind!=CardType.Equipment&&p.Card.Kind!=CardType.Enchantment&&Enemies(seat,p.Owner)).Select(p=>p.Owner).Distinct().Count()>1)break;
                        var attack=New(ActionKind.Attack,b);attack.units=new[]{a};result.Add(attack);
                        if(!attacks.ContainsKey(b))attacks[b]=new List<int>();attacks[b].Add(a);break;
                    case "activate":result.Add(New(ActionKind.Activate,unit:a));break;
                    case "terrainAbility":result.Add(New(ActionKind.ActivateTerrain,a));break;
                    case "equip":result.Add(New(ActionKind.Equip,b,a));break;
                    case "board":result.Add(New(ActionKind.BoardVehicle,b,a));break;
                    case "disembark":result.Add(New(ActionKind.DisembarkVehicle,unit:a));break;
                    case "exile":result.Add(New(ActionKind.CastExiled,a));break;
                }
            }
            foreach(var group in attacks.Where(g=>g.Value.Count>1)){var c=New(ActionKind.Attack,group.Key);c.units=group.Value.ToArray();result.Add(c);}
            if(stack.Count>0||Phase==Stage.Main||Phase==Stage.End)result.Add(New(ActionKind.Pass));
            if(Priority==Active&&stack.Count==0&&(Phase==Stage.Main||Phase==Stage.End||Phase==Stage.Terrain&&(Placed||!Enumerable.Range(0,4).Any(p=>seats[seat].Top(p)!=null)||!Enumerable.Range(0,121).Any(CanPlace))))result.Add(New(ActionKind.NextPhase));
            return result;
        }
    }
}
